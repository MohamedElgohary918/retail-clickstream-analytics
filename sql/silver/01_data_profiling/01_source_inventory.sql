-- STEP 1 | SOURCE INVENTORY
-- Q01: Source inventory / metadata (ALREADY RUN)
SELECT
    t.TABLE_NAME,
    t.TABLE_TYPE,
    t.ROW_COUNT,
    t.BYTES
FROM RETAIL_CLICKSTREAM_DB.INFORMATION_SCHEMA.TABLES AS t
WHERE t.TABLE_SCHEMA = 'RAW'
  AND t.TABLE_NAME IN (
      'RAW_CUSTOMERS', 'RAW_PRODUCTS', 'RAW_ORDERS',
      'RAW_ORDER_ITEMS', 'RAW_INVENTORY', 'RAW_CLICKSTREAM_EVENTS'
  )
ORDER BY t.TABLE_NAME;
