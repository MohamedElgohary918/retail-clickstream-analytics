-- ============================================================================
-- 06_orchestration / 04_create_tasks.sql
-- STEP 4: Create the Gold-refresh task graph. ALL TASKS ARE CREATED SUSPENDED -
--         nothing runs until Step 6.
--
--   TSK_GATE  (root, every 15 min)  -> calls SP_SILVER_GATE, publishes READY / INVESTIGATE
--    |-- TSK_DIM_CUSTOMER
--    |-- TSK_DIM_DATE
--    |-- TSK_DIM_PRODUCT
--    |-- TSK_FACT_ORDER_ITEMS
--    |-- TSK_FACT_CLICKSTREAM_EVENTS
--    '-- TSK_INVENTORY_SNAPSHOT --> TSK_DIM_INVENTORY
--
-- Every child runs only when the gate said READY. (Validation + finalizer = Step 5.)
-- Safe to re-run: the root is suspended first and every task is re-created.
-- ============================================================================

-- ============================================================================
-- A. PRIVILEGE CHECK (run as DBT_SILVER_ROLE)
-- Expect: EXECUTE TASK on ACCOUNT, and CREATE TASK on schema MARTS
-- (or OWNERSHIP of the MARTS schema). If a row is missing, hand section B to an admin.
-- ============================================================================
USE ROLE DBT_SILVER_ROLE;
SHOW GRANTS TO ROLE DBT_SILVER_ROLE;
SELECT "privilege", "granted_on", "name"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
WHERE "privilege" IN ('EXECUTE TASK', 'CREATE TASK', 'OWNERSHIP')
  AND ("granted_on" IN ('ACCOUNT', 'SCHEMA'))
ORDER BY 1, 2, 3;


-- ============================================================================
-- C. CREATE THE TASKS
-- ============================================================================
USE ROLE DBT_SILVER_ROLE;
USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_CLICKSTREAM_DB;
USE SCHEMA MARTS;

-- A graph can only be changed while its root is suspended
ALTER TASK IF EXISTS RETAIL_CLICKSTREAM_DB.MARTS.TSK_GATE SUSPEND;


-- ---------------------------------------------------------------------------
-- C1. ROOT: the gate. Runs SP_SILVER_GATE and publishes its status
--     ('READY' or 'INVESTIGATE') as the task's return value for the children.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TASK RETAIL_CLICKSTREAM_DB.MARTS.TSK_GATE
    WAREHOUSE = RETAIL_WH
    SCHEDULE = '15 MINUTE'
    ALLOW_OVERLAPPING_EXECUTION = FALSE
    SUSPEND_TASK_AFTER_NUM_FAILURES = 3
    USER_TASK_TIMEOUT_MS = 600000
    COMMENT = 'Root: Silver readiness gate. Publishes READY / INVESTIGATE.'
AS
EXECUTE IMMEDIATE $$
DECLARE
    v_result VARCHAR;
    v_status VARCHAR;
BEGIN
    CALL RETAIL_CLICKSTREAM_DB.MARTS.SP_SILVER_GATE() INTO :v_result;
    v_status := SPLIT_PART(:v_result, ':', 1);
    CALL SYSTEM$SET_RETURN_VALUE(:v_status);
END;
$$;


-- ---------------------------------------------------------------------------
-- C2. TSK_DIM_CUSTOMER
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TASK RETAIL_CLICKSTREAM_DB.MARTS.TSK_DIM_CUSTOMER
    WAREHOUSE = RETAIL_WH
    USER_TASK_TIMEOUT_MS = 600000
    AFTER RETAIL_CLICKSTREAM_DB.MARTS.TSK_GATE
    WHEN SYSTEM$GET_PREDECESSOR_RETURN_VALUE('TSK_GATE') = 'READY'
AS
MERGE INTO RETAIL_CLICKSTREAM_DB.MARTS.DIM_CUSTOMER AS t
USING (
    SELECT CUSTOMER_ID, FIRST_NAME, LAST_NAME, EMAIL, COUNTRY, REGISTRATION_DATE
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CUSTOMERS
) AS s
ON t.CUSTOMER_ID = s.CUSTOMER_ID
WHEN MATCHED AND (
       t.FIRST_NAME        IS DISTINCT FROM s.FIRST_NAME
    OR t.LAST_NAME         IS DISTINCT FROM s.LAST_NAME
    OR t.EMAIL             IS DISTINCT FROM s.EMAIL
    OR t.COUNTRY           IS DISTINCT FROM s.COUNTRY
    OR t.REGISTRATION_DATE IS DISTINCT FROM s.REGISTRATION_DATE
) THEN UPDATE SET
    t.FIRST_NAME        = s.FIRST_NAME,
    t.LAST_NAME         = s.LAST_NAME,
    t.EMAIL             = s.EMAIL,
    t.COUNTRY           = s.COUNTRY,
    t.REGISTRATION_DATE = s.REGISTRATION_DATE
WHEN NOT MATCHED THEN INSERT
    (CUSTOMER_ID, FIRST_NAME, LAST_NAME, EMAIL, COUNTRY, REGISTRATION_DATE)
VALUES
    (s.CUSTOMER_ID, s.FIRST_NAME, s.LAST_NAME, s.EMAIL, s.COUNTRY, s.REGISTRATION_DATE);


-- ---------------------------------------------------------------------------
-- C3. TSK_DIM_DATE
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TASK RETAIL_CLICKSTREAM_DB.MARTS.TSK_DIM_DATE
    WAREHOUSE = RETAIL_WH
    USER_TASK_TIMEOUT_MS = 600000
    AFTER RETAIL_CLICKSTREAM_DB.MARTS.TSK_GATE
    WHEN SYSTEM$GET_PREDECESSOR_RETURN_VALUE('TSK_GATE') = 'READY'
AS
MERGE INTO RETAIL_CLICKSTREAM_DB.MARTS.DIM_DATE AS t
USING (
    SELECT DISTINCT
        ORDER_TIMESTAMP,
        TO_DATE(ORDER_TIMESTAMP)   AS FULL_DATE,
        YEAR(ORDER_TIMESTAMP)      AS YEAR,
        QUARTER(ORDER_TIMESTAMP)   AS QUARTER,
        MONTH(ORDER_TIMESTAMP)     AS MONTH,
        DAY(ORDER_TIMESTAMP)       AS DAY,
        DAYNAME(ORDER_TIMESTAMP)   AS DAY_OF_WEEK,
        MONTHNAME(ORDER_TIMESTAMP) AS MONTH_NAME
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDERS
    WHERE ORDER_TIMESTAMP IS NOT NULL
) AS s
ON t.ORDER_TIMESTAMP = s.ORDER_TIMESTAMP
WHEN MATCHED AND (
       t.FULL_DATE   IS DISTINCT FROM s.FULL_DATE
    OR t.YEAR        IS DISTINCT FROM s.YEAR
    OR t.QUARTER     IS DISTINCT FROM s.QUARTER
    OR t.MONTH       IS DISTINCT FROM s.MONTH
    OR t.DAY         IS DISTINCT FROM s.DAY
    OR t.DAY_OF_WEEK IS DISTINCT FROM s.DAY_OF_WEEK
    OR t.MONTH_NAME  IS DISTINCT FROM s.MONTH_NAME
) THEN UPDATE SET
    t.FULL_DATE   = s.FULL_DATE,
    t.YEAR        = s.YEAR,
    t.QUARTER     = s.QUARTER,
    t.MONTH       = s.MONTH,
    t.DAY         = s.DAY,
    t.DAY_OF_WEEK = s.DAY_OF_WEEK,
    t.MONTH_NAME  = s.MONTH_NAME
WHEN NOT MATCHED THEN INSERT
    (ORDER_TIMESTAMP, FULL_DATE, YEAR, QUARTER, MONTH, DAY, DAY_OF_WEEK, MONTH_NAME)
VALUES
    (s.ORDER_TIMESTAMP, s.FULL_DATE, s.YEAR, s.QUARTER, s.MONTH, s.DAY, s.DAY_OF_WEEK, s.MONTH_NAME);


