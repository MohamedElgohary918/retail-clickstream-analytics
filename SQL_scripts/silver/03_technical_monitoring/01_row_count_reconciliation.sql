-- MONITOR 01: RAW versus STAGING row preservation (all six sources)
-- Read-only. A discrepancy means investigate; it does not diagnose the cause.
WITH source_counts AS (
    SELECT 'CUSTOMERS' AS DATASET, (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CUSTOMERS) AS RAW_ROWS,
           (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CUSTOMERS) AS STAGING_ROWS
    UNION ALL
    SELECT 'PRODUCTS', (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_PRODUCTS),
           (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_PRODUCTS)
    UNION ALL
    SELECT 'ORDERS', (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDERS),
           (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDERS)
    UNION ALL
    SELECT 'ORDER_ITEMS', (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS),
           (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDER_ITEMS)
    UNION ALL
    SELECT 'INVENTORY', (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_INVENTORY),
           (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_INVENTORY)
    UNION ALL
    SELECT 'CLICKSTREAM_EVENTS', (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS),
           (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS)
)
SELECT
    s.DATASET,
    s.RAW_ROWS,
    s.STAGING_ROWS,
    s.STAGING_ROWS - s.RAW_ROWS AS ROW_DIFFERENCE,
    IFF(s.RAW_ROWS = s.STAGING_ROWS, 'PASS', 'INVESTIGATE') AS STATUS
FROM source_counts AS s
ORDER BY s.DATASET;
