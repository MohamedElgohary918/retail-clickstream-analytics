-- MONITOR 02: Compare clickstream counts and replay/historical timestamps.
-- SIMULATED_AT is a replay timestamp, NOT a confirmed Snowflake ingestion timestamp.
-- No freshness SLA is assumed: the Kafka replay can intentionally be paused.
WITH raw_stats AS (
    SELECT COUNT(*) AS EVENT_ROWS,
           MIN(e.EVENT_TIME) AS EARLIEST_EVENT_TIME,
           MAX(e.EVENT_TIME) AS LATEST_EVENT_TIME,
           MAX(e.SIMULATED_AT) AS LATEST_REPLAY_TIMESTAMP
    FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
), staging_stats AS (
    SELECT COUNT(*) AS EVENT_ROWS,
           MIN(e.EVENT_TIME) AS EARLIEST_EVENT_TIME,
           MAX(e.EVENT_TIME) AS LATEST_EVENT_TIME,
           MAX(e.SIMULATED_AT) AS LATEST_REPLAY_TIMESTAMP
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS AS e
)
SELECT
    CURRENT_TIMESTAMP() AS CHECKED_AT,
    r.EVENT_ROWS AS RAW_EVENTS,
    s.EVENT_ROWS AS STAGING_EVENTS,
    s.EVENT_ROWS - r.EVENT_ROWS AS EVENT_ROW_DIFFERENCE,
    r.LATEST_EVENT_TIME AS RAW_LATEST_HISTORICAL_TIME,
    s.LATEST_EVENT_TIME AS STAGING_LATEST_HISTORICAL_TIME,
    r.LATEST_REPLAY_TIMESTAMP AS RAW_LATEST_REPLAY_TIME,
    s.LATEST_REPLAY_TIMESTAMP AS STAGING_LATEST_REPLAY_TIME,
    CASE
        WHEN r.EVENT_ROWS = s.EVENT_ROWS
            AND EQUAL_NULL(r.EARLIEST_EVENT_TIME, s.EARLIEST_EVENT_TIME)
            AND EQUAL_NULL(r.LATEST_EVENT_TIME, s.LATEST_EVENT_TIME)
            AND EQUAL_NULL(r.LATEST_REPLAY_TIMESTAMP, s.LATEST_REPLAY_TIMESTAMP)
            THEN 'PASS'
        ELSE 'INVESTIGATE'
    END AS CHECKPOINT_STATUS
FROM raw_stats AS r
CROSS JOIN staging_stats AS s;
