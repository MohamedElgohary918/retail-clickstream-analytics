-- STEP 2 | EVENT TYPES + HISTORICAL/REPLAY TIME RANGE
-- Q02: Clickstream event distribution (ALREADY RUN)
SELECT
    e.EVENT_TYPE,
    COUNT(*) AS EVENT_COUNT,
    MIN(e.EVENT_TIME) AS FIRST_EVENT_TIME,
    MAX(e.EVENT_TIME) AS LAST_EVENT_TIME,
    MIN(e.SIMULATED_AT) AS FIRST_SIMULATED_AT,
    MAX(e.SIMULATED_AT) AS LAST_SIMULATED_AT
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
GROUP BY e.EVENT_TYPE
ORDER BY EVENT_COUNT DESC;
