-- STEP 5 | REFERENTIAL INTEGRITY: OLTP VS OLTP / STREAM VS OLTP
-- Q15: Orders with no matching customer (excluding NULL foreign keys, counted Q05)
SELECT
    COUNT(*) AS ORDERS_WITH_MISSING_CUSTOMER_REFERENCE
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDERS AS o
WHERE o.CUSTOMER_ID IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CUSTOMERS AS c
      WHERE c.CUSTOMER_ID = o.CUSTOMER_ID
  );

