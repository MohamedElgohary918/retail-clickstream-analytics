-- STEP 4 | UNIQUENESS, VALUES, NUMERIC RANGES, CONSISTENCY
-- Q09: Business-key uniqueness. DUPLICATE_EXTRA_ROWS is a CANDIDATE issue.
SELECT 'RAW_CUSTOMERS' AS TABLE_NAME, 'CUSTOMER_ID' AS KEY_NAME,
       COUNT(*) AS TOTAL_ROWS, COUNT(DISTINCT c.CUSTOMER_ID) AS DISTINCT_NON_NULL_KEYS,
       COUNT(*) - COUNT(DISTINCT c.CUSTOMER_ID) - SUM(IFF(c.CUSTOMER_ID IS NULL, 1, 0)) AS DUPLICATE_EXTRA_ROWS
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CUSTOMERS AS c
UNION ALL
SELECT 'RAW_PRODUCTS', 'PRODUCT_ID', COUNT(*), COUNT(DISTINCT p.PRODUCT_ID),
       COUNT(*) - COUNT(DISTINCT p.PRODUCT_ID) - SUM(IFF(p.PRODUCT_ID IS NULL, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_PRODUCTS AS p
UNION ALL
SELECT 'RAW_ORDERS', 'ORDER_ID', COUNT(*), COUNT(DISTINCT o.ORDER_ID),
       COUNT(*) - COUNT(DISTINCT o.ORDER_ID) - SUM(IFF(o.ORDER_ID IS NULL, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDERS AS o
UNION ALL
SELECT 'RAW_ORDER_ITEMS', 'ORDER_ITEM_ID', COUNT(*), COUNT(DISTINCT i.ORDER_ITEM_ID),
       COUNT(*) - COUNT(DISTINCT i.ORDER_ITEM_ID) - SUM(IFF(i.ORDER_ITEM_ID IS NULL, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS AS i
UNION ALL
SELECT 'RAW_INVENTORY', 'PRODUCT_ID', COUNT(*), COUNT(DISTINCT v.PRODUCT_ID),
       COUNT(*) - COUNT(DISTINCT v.PRODUCT_ID) - SUM(IFF(v.PRODUCT_ID IS NULL, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_INVENTORY AS v
ORDER BY TABLE_NAME;

-- Q10: Actual ORDER_STATUS values (do not assume values in advance)
SELECT
    COALESCE(UPPER(TRIM(o.ORDER_STATUS)), '<NULL>') AS NORMALIZED_ORDER_STATUS,
    COUNT(*) AS ROW_COUNT
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDERS AS o
GROUP BY 1
ORDER BY ROW_COUNT DESC;

-- Q11: Numeric validation summarized across columns; negatives are flags, not auto-deletions.
SELECT 'PRODUCTS.PRICE' AS COLUMN_NAME, COUNT(*) AS ROW_COUNT,
       MIN(p.PRICE) AS MIN_VALUE, MAX(p.PRICE) AS MAX_VALUE,
       SUM(IFF(p.PRICE < 0, 1, 0)) AS NEGATIVE_ROWS,
       SUM(IFF(p.PRICE = 0, 1, 0)) AS ZERO_ROWS
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_PRODUCTS AS p
UNION ALL
SELECT 'PRODUCTS.COST', COUNT(*), MIN(p.COST), MAX(p.COST),
       SUM(IFF(p.COST < 0, 1, 0)), SUM(IFF(p.COST = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_PRODUCTS AS p
UNION ALL
SELECT 'ORDERS.ORDER_TOTAL', COUNT(*), MIN(o.ORDER_TOTAL), MAX(o.ORDER_TOTAL),
       SUM(IFF(o.ORDER_TOTAL < 0, 1, 0)), SUM(IFF(o.ORDER_TOTAL = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDERS AS o
UNION ALL
SELECT 'ORDER_ITEMS.QUANTITY', COUNT(*), MIN(i.QUANTITY), MAX(i.QUANTITY),
       SUM(IFF(i.QUANTITY < 0, 1, 0)), SUM(IFF(i.QUANTITY = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS AS i
UNION ALL
SELECT 'ORDER_ITEMS.UNIT_PRICE', COUNT(*), MIN(i.UNIT_PRICE), MAX(i.UNIT_PRICE),
       SUM(IFF(i.UNIT_PRICE < 0, 1, 0)), SUM(IFF(i.UNIT_PRICE = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS AS i
UNION ALL
SELECT 'ORDER_ITEMS.LINE_TOTAL', COUNT(*), MIN(i.LINE_TOTAL), MAX(i.LINE_TOTAL),
       SUM(IFF(i.LINE_TOTAL < 0, 1, 0)), SUM(IFF(i.LINE_TOTAL = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS AS i
UNION ALL
SELECT 'INVENTORY.STOCK_QUANTITY', COUNT(*), MIN(v.STOCK_QUANTITY), MAX(v.STOCK_QUANTITY),
       SUM(IFF(v.STOCK_QUANTITY < 0, 1, 0)), SUM(IFF(v.STOCK_QUANTITY = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_INVENTORY AS v
UNION ALL
SELECT 'INVENTORY.REORDER_LEVEL', COUNT(*), MIN(v.REORDER_LEVEL), MAX(v.REORDER_LEVEL),
       SUM(IFF(v.REORDER_LEVEL < 0, 1, 0)), SUM(IFF(v.REORDER_LEVEL = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_INVENTORY AS v
UNION ALL
SELECT 'CLICKSTREAM.PRICE', COUNT(*), MIN(e.PRICE), MAX(e.PRICE),
       SUM(IFF(e.PRICE < 0, 1, 0)), SUM(IFF(e.PRICE = 0, 1, 0))
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
ORDER BY COLUMN_NAME;

-- Q12: ORDER_ITEMS.LINE_TOTAL vs QUANTITY * UNIT_PRICE (rounding tolerance 0.01)
SELECT
    COUNT(*) AS TOTAL_ORDER_ITEMS,
    SUM(IFF(i.QUANTITY IS NOT NULL AND i.UNIT_PRICE IS NOT NULL AND i.LINE_TOTAL IS NOT NULL
            AND ABS(i.LINE_TOTAL - (i.QUANTITY * i.UNIT_PRICE)) > 0.01, 1, 0)) AS MISMATCHED_LINE_TOTAL,
    MAX(ABS(i.LINE_TOTAL - (i.QUANTITY * i.UNIT_PRICE))) AS MAX_ABSOLUTE_DIFFERENCE
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS AS i;

-- Q13: Order header total vs sum of order lines; may differ due to discounts/shipping/tax.
WITH item_sums AS (
    SELECT
        i.ORDER_ID,
        SUM(i.LINE_TOTAL) AS SUM_LINE_TOTAL,
        COUNT(*) AS LINE_COUNT
    FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS AS i
    WHERE i.ORDER_ID IS NOT NULL
    GROUP BY i.ORDER_ID
)
SELECT
    COUNT(*) AS ORDERS_WITH_ITEMS,
    SUM(IFF(o.ORDER_TOTAL IS NOT NULL AND s.SUM_LINE_TOTAL IS NOT NULL
            AND ABS(o.ORDER_TOTAL - s.SUM_LINE_TOTAL) > 0.01, 1, 0)) AS DIFFERENT_TOTALS,
    MAX(ABS(o.ORDER_TOTAL - s.SUM_LINE_TOTAL)) AS MAX_ABSOLUTE_DIFFERENCE,
    MIN(s.LINE_COUNT) AS MIN_LINES_PER_ORDER,
    MAX(s.LINE_COUNT) AS MAX_LINES_PER_ORDER
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDERS AS o
JOIN item_sums AS s ON o.ORDER_ID = s.ORDER_ID;

-- Q14: Possible identical clickstream payloads, excluding SIMULATED_AT.
-- WARNING: identical payload does not necessarily prove duplicate real-world events.
WITH identical_payload_groups AS (
    SELECT
        e.EVENT_TIME, e.EVENT_TYPE, e.PRODUCT_ID, e.CATEGORY_ID,
        e.CATEGORY_CODE, e.BRAND, e.PRICE, e.USER_ID, e.USER_SESSION,
        COUNT(*) AS ROWS_IN_GROUP
    FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
    GROUP BY
        e.EVENT_TIME, e.EVENT_TYPE, e.PRODUCT_ID, e.CATEGORY_ID,
        e.CATEGORY_CODE, e.BRAND, e.PRICE, e.USER_ID, e.USER_SESSION
    HAVING COUNT(*) > 1
)
SELECT
    COUNT(*) AS IDENTICAL_PAYLOAD_GROUPS,
    COALESCE(SUM(ROWS_IN_GROUP), 0) AS ROWS_IN_IDENTICAL_GROUPS,
    COALESCE(SUM(ROWS_IN_GROUP - 1), 0) AS EXTRA_IDENTICAL_PAYLOAD_ROWS
FROM identical_payload_groups;
