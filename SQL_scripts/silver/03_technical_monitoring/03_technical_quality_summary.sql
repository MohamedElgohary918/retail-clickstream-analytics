-- MONITOR 03: Critical quality problems in the six STAGING views.
-- Checks mirror the Phase 3 technical validations; NOT business KPI definitions.
-- One row per source. Missing optional brand/category values are monitored separately.
WITH quality AS (
    SELECT 'CUSTOMERS' AS DATASET,
           COUNT(*) AS ROWS_CHECKED,
           COUNT_IF(c.CUSTOMER_ID IS NULL OR c.EMAIL IS NULL
                    OR TRIM(c.EMAIL) = ''
                    OR c.EMAIL <> LOWER(TRIM(c.EMAIL))
                    OR c.REGISTRATION_DATE IS NULL) AS CRITICAL_ISSUE_ROWS
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CUSTOMERS AS c

    UNION ALL
    SELECT 'PRODUCTS', COUNT(*),
           COUNT_IF(p.PRODUCT_ID IS NULL OR p.PRICE IS NULL OR p.COST IS NULL
                    OR p.IS_NEGATIVE_PRICE OR p.IS_NEGATIVE_COST)
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_PRODUCTS AS p

    UNION ALL
    SELECT 'ORDERS', COUNT(*),
           COUNT_IF(o.ORDER_ID IS NULL OR o.CUSTOMER_ID IS NULL
                    OR o.HAS_INVALID_ORDER_TOTAL OR o.IS_MISSING_ORDER_TIMESTAMP)
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDERS AS o

    UNION ALL
    SELECT 'ORDER_ITEMS', COUNT(*),
           COUNT_IF(i.ORDER_ITEM_ID IS NULL OR i.ORDER_ID IS NULL OR i.PRODUCT_ID IS NULL
                    OR i.HAS_LINE_TOTAL_MISMATCH OR i.HAS_INVALID_QUANTITY
                    OR i.HAS_INVALID_UNIT_PRICE OR i.HAS_INVALID_LINE_TOTAL)
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDER_ITEMS AS i

    UNION ALL
    SELECT 'INVENTORY', COUNT(*),
           COUNT_IF(i.PRODUCT_ID IS NULL OR i.HAS_INVALID_STOCK_QUANTITY
                    OR i.HAS_INVALID_REORDER_LEVEL)
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_INVENTORY AS i

    UNION ALL
    SELECT 'CLICKSTREAM_EVENTS', COUNT(*),
           COUNT_IF(e.EVENT_ID IS NULL OR e.EVENT_TYPE IS NULL OR e.EVENT_TYPE NOT IN ('view', 'cart', 'purchase', 'remove_from_cart')
                    OR e.PRODUCT_ID IS NULL OR e.HAS_INVALID_PRICE
                    OR e.HAS_INVALID_SESSION_ID OR e.HAS_MISSING_TIMESTAMPS)
    FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS AS e
)
SELECT
    q.DATASET,
    q.ROWS_CHECKED,
    COALESCE(q.CRITICAL_ISSUE_ROWS, 0) AS CRITICAL_ISSUE_ROWS,
    IFF(COALESCE(q.CRITICAL_ISSUE_ROWS, 0) = 0, 'PASS', 'INVESTIGATE') AS QUALITY_STATUS
FROM quality AS q
ORDER BY q.DATASET;
