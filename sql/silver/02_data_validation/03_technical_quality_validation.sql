-- PHASE 3 VALIDATION: run each query separately in Snowflake, read-only.
-- Query 1. Same number of source and staging records for all 6 independent tables.
WITH counts AS (
    SELECT 'CUSTOMERS' AS TABLE_NAME,
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CUSTOMERS) AS RAW_ROWS,
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CUSTOMERS) AS STAGING_ROWS
    UNION ALL
    SELECT 'PRODUCTS',
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_PRODUCTS),
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_PRODUCTS)
    UNION ALL
    SELECT 'ORDERS',
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDERS),
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDERS)
    UNION ALL
    SELECT 'ORDER_ITEMS',
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_ORDER_ITEMS),
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDER_ITEMS)
    UNION ALL
    SELECT 'INVENTORY',
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_INVENTORY),
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_INVENTORY)
    UNION ALL
    SELECT 'CLICKSTREAM_EVENTS',
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS),
        (SELECT COUNT(*) FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS)
)
SELECT c.TABLE_NAME, c.RAW_ROWS, c.STAGING_ROWS,
       c.STAGING_ROWS - c.RAW_ROWS AS ROW_DIFFERENCE,
       IFF(c.RAW_ROWS = c.STAGING_ROWS, 'PASS', 'FAIL') AS VALIDATION_STATUS
FROM counts AS c
ORDER BY c.TABLE_NAME;

-- Query 2. Quality indicator metrics: EXPECT some nonzero counts for valid missing/zero values.
SELECT 'PRODUCTS' AS SOURCE_NAME,
    COUNT_IF(p.IS_MISSING_CATEGORY_CODE) AS MISSING_CATEGORY,
    COUNT_IF(p.IS_MISSING_BRAND) AS MISSING_BRAND,
    COUNT_IF(p.IS_ZERO_PRICE) AS ZERO_PRICE,
    COUNT_IF(p.IS_NEGATIVE_PRICE OR p.IS_NEGATIVE_COST) AS INVALID_NUMBERS
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_PRODUCTS AS p
UNION ALL
SELECT 'CLICKSTREAM_EVENTS',
    COUNT_IF(e.IS_MISSING_CATEGORY_CODE),
    COUNT_IF(e.IS_MISSING_BRAND),
    COUNT_IF(e.IS_ZERO_PRICE),
    COUNT_IF(e.HAS_INVALID_PRICE)
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS AS e;

-- Query 3. Critical quality flags should all be zero at the current baseline.
SELECT 'ORDERS' AS SOURCE_NAME,
    COUNT_IF(o.HAS_INVALID_ORDER_TOTAL OR o.IS_MISSING_ORDER_TIMESTAMP) AS INVALID_ROWS
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDERS AS o
UNION ALL
SELECT 'ORDER_ITEMS',
    COUNT_IF(i.HAS_LINE_TOTAL_MISMATCH OR i.HAS_INVALID_QUANTITY
        OR i.HAS_INVALID_UNIT_PRICE OR i.HAS_INVALID_LINE_TOTAL)
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDER_ITEMS AS i
UNION ALL
SELECT 'INVENTORY',
    COUNT_IF(i.HAS_INVALID_STOCK_QUANTITY OR i.HAS_INVALID_REORDER_LEVEL)
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_INVENTORY AS i
UNION ALL
SELECT 'CLICKSTREAM_EVENTS',
    COUNT_IF(e.HAS_INVALID_PRICE OR e.HAS_INVALID_SESSION_ID OR e.HAS_MISSING_TIMESTAMPS)
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS AS e;

-- Query 4. Historical payload similarity diagnostic: audit only; prefer EVENT_ID integrity for uniqueness.
-- One output row per exact payload pattern repeated at least twice.
SELECT
    e.EVENT_TIME, e.EVENT_TYPE, e.PRODUCT_ID, e.CATEGORY_ID,
    e.CATEGORY_CODE, e.BRAND, e.PRICE, e.USER_ID,
    e.USER_SESSION, e.SIMULATED_AT,
    COUNT(*) AS REPEAT_COUNT,
    COUNT(*) - 1 AS EXTRA_IDENTICAL_PAYLOAD_ROWS
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
GROUP BY
    e.EVENT_TIME, e.EVENT_TYPE, e.PRODUCT_ID, e.CATEGORY_ID,
    e.CATEGORY_CODE, e.BRAND, e.PRICE, e.USER_ID,
    e.USER_SESSION, e.SIMULATED_AT
HAVING COUNT(*) > 1
ORDER BY REPEAT_COUNT DESC;

-- Query 5. Streaming checkpoint before/after teammate resumes Kafka replay.
-- SIMULATED_AT is a replay timestamp; it does not prove Snowflake ingestion time.
SELECT
    'RAW' AS LAYER_NAME,
    COUNT(*) AS EVENT_ROWS,
    MAX(e.EVENT_TIME) AS LATEST_HISTORICAL_EVENT_TIME,
    MAX(e.SIMULATED_AT) AS LATEST_REPLAY_TIMESTAMP
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
UNION ALL
SELECT
    'STAGING',
    COUNT(*),
    MAX(e.EVENT_TIME),
    MAX(e.SIMULATED_AT)
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS AS e;
