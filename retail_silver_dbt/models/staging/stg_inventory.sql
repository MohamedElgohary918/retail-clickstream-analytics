-- Stock = 0 is a valid operational state, not a bad record.
SELECT
    i.PRODUCT_ID,
    i.STOCK_QUANTITY,
    i.REORDER_LEVEL,
    NULLIF(TRIM(i.INVENTORY_ORIGIN), '') AS INVENTORY_ORIGIN,
    (i.STOCK_QUANTITY = 0) AS IS_OUT_OF_STOCK,
    (i.STOCK_QUANTITY <= i.REORDER_LEVEL) AS IS_AT_OR_BELOW_REORDER_LEVEL,
    (i.STOCK_QUANTITY IS NULL OR i.STOCK_QUANTITY < 0) AS HAS_INVALID_STOCK_QUANTITY,
    (i.REORDER_LEVEL IS NULL OR i.REORDER_LEVEL < 0) AS HAS_INVALID_REORDER_LEVEL,
    (NULLIF(TRIM(i.INVENTORY_ORIGIN), '') IS NULL) AS IS_MISSING_INVENTORY_ORIGIN
FROM {{ source('retail_raw', 'inventory') }} AS i
