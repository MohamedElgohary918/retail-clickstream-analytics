-- STAGING standardized text checks. Each row reports violations of one technical rule.
-- These are simple display/standardization checks, NOT full address or business validation.
SELECT 'CUSTOMERS_EMAIL' AS CHECK_NAME,
       COUNT_IF(c.EMAIL IS NULL OR c.EMAIL <> LOWER(TRIM(c.EMAIL))) AS INVALID_ROWS
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CUSTOMERS AS c
UNION ALL
SELECT 'ORDERS_STATUS',
       COUNT_IF(o.ORDER_STATUS IS NULL OR o.ORDER_STATUS <> UPPER(TRIM(o.ORDER_STATUS)))
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_ORDERS AS o
UNION ALL
SELECT 'CLICKSTREAM_EVENT_TYPE',
       COUNT_IF(e.EVENT_TYPE IS NULL OR e.EVENT_TYPE <> LOWER(TRIM(e.EVENT_TYPE)))
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS AS e;
