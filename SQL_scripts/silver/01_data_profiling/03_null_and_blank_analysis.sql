-- STEP 3 | NULL AND BLANK ANALYSIS
-- Missing keys are not automatically removed; NULL brand/category_code can be valid.
-- Q03: CUSTOMERS completeness
SELECT
    COUNT(*) AS TOTAL_ROWS,
    SUM(IFF(c.CUSTOMER_ID IS NULL, 1, 0)) AS MISSING_CUSTOMER_ID,
    SUM(IFF(c.FIRST_NAME IS NULL OR TRIM(c.FIRST_NAME) = '', 1, 0)) AS MISSING_FIRST_NAME,
    SUM(IFF(c.LAST_NAME IS NULL OR TRIM(c.LAST_NAME) = '', 1, 0)) AS MISSING_LAST_NAME,
    SUM(IFF(c.EMAIL IS NULL OR TRIM(c.EMAIL) = '', 1, 0)) AS MISSING_EMAIL,
    SUM(IFF(c.COUNTRY IS NULL OR TRIM(c.COUNTRY) = '', 1, 0)) AS MISSING_COUNTRY,
    SUM(IFF(c.REGISTRATION_DATE IS NULL, 1, 0)) AS MISSING_REGISTRATION_DATE
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CUSTOMERS AS c;

