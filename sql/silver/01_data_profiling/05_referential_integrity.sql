-- Q20: TEST ONLY: clickstream USER_ID to CUSTOMER_ID and PRODUCT_ID to PRODUCT_ID.
-- These may be DIFFERENT namespaces; an unmatched ID is NOT necessarily an error.
SELECT
    COUNT(*) AS TOTAL_EVENTS,
    SUM(IFF(e.USER_ID IS NOT NULL AND c.CUSTOMER_ID IS NOT NULL, 1, 0)) AS EVENTS_MATCHING_CUSTOMER_ID,
    SUM(IFF(e.USER_ID IS NOT NULL AND c.CUSTOMER_ID IS NULL, 1, 0)) AS EVENTS_WITHOUT_CUSTOMER_ID_MATCH,
    SUM(IFF(e.PRODUCT_ID IS NOT NULL AND p.PRODUCT_ID IS NOT NULL, 1, 0)) AS EVENTS_MATCHING_PRODUCT_ID,
    SUM(IFF(e.PRODUCT_ID IS NOT NULL AND p.PRODUCT_ID IS NULL, 1, 0)) AS EVENTS_WITHOUT_PRODUCT_ID_MATCH
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
LEFT JOIN (
    SELECT DISTINCT CUSTOMER_ID
    FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CUSTOMERS
    WHERE CUSTOMER_ID IS NOT NULL
) AS c ON e.USER_ID = c.CUSTOMER_ID
LEFT JOIN (
    SELECT DISTINCT PRODUCT_ID
    FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_PRODUCTS
    WHERE PRODUCT_ID IS NOT NULL
) AS p ON e.PRODUCT_ID = p.PRODUCT_ID;
