-- STEP 6 | STREAMING BEHAVIOR AND TIMESTAMPS
-- Q21: Stream coverage, counts, session cardinality and replay timing.
-- SIMULATED_AT is not confirmed as Snowflake arrival timestamp. Do not call this 'true ingestion lag'.
SELECT
    COUNT(*) AS TOTAL_EVENTS,
    COUNT(DISTINCT e.USER_ID) AS DISTINCT_USERS,
    COUNT(DISTINCT e.USER_SESSION) AS DISTINCT_SESSION_IDS,
    COUNT(DISTINCT e.PRODUCT_ID) AS DISTINCT_PRODUCTS,
    MIN(e.EVENT_TIME) AS MIN_EVENT_TIME,
    MAX(e.EVENT_TIME) AS MAX_EVENT_TIME,
    MIN(e.SIMULATED_AT) AS MIN_SIMULATED_AT,
    MAX(e.SIMULATED_AT) AS MAX_SIMULATED_AT,
    SUM(IFF(e.SIMULATED_AT IS NOT NULL AND e.EVENT_TIME IS NOT NULL
            AND e.SIMULATED_AT < e.EVENT_TIME, 1, 0)) AS SIMULATED_EARLIER_THAN_EVENT
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e;

-- Q22: Session sizes and time spans observed in sample.
-- GROUP BY both USER_ID and USER_SESSION to avoid mixing users.
WITH sessions AS (
    SELECT
        e.USER_ID, e.USER_SESSION,
        COUNT(*) AS EVENTS_PER_SESSION,
        MIN(e.EVENT_TIME) AS FIRST_EVENT,
        MAX(e.EVENT_TIME) AS LAST_EVENT,
        SUM(IFF(e.EVENT_TYPE = 'view', 1, 0)) AS VIEW_EVENTS,
        SUM(IFF(e.EVENT_TYPE = 'cart', 1, 0)) AS CART_EVENTS,
        SUM(IFF(e.EVENT_TYPE = 'purchase', 1, 0)) AS PURCHASE_EVENTS
    FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
    WHERE e.USER_SESSION IS NOT NULL AND e.USER_ID IS NOT NULL
    GROUP BY e.USER_ID, e.USER_SESSION
)
SELECT
    COUNT(*) AS SESSIONS,
    MIN(EVENTS_PER_SESSION) AS MIN_EVENTS_PER_SESSION,
    ROUND(AVG(EVENTS_PER_SESSION), 2) AS AVG_EVENTS_PER_SESSION,
    MAX(EVENTS_PER_SESSION) AS MAX_EVENTS_PER_SESSION,
    SUM(IFF(EVENTS_PER_SESSION = 1, 1, 0)) AS SINGLE_EVENT_SESSIONS,
    SUM(IFF(CART_EVENTS > 0, 1, 0)) AS SESSIONS_WITH_CART,
    SUM(IFF(PURCHASE_EVENTS > 0, 1, 0)) AS SESSIONS_WITH_PURCHASE,
    MAX(DATEDIFF('second', FIRST_EVENT, LAST_EVENT)) AS MAX_OBSERVED_SPAN_SECONDS
FROM sessions;

-- Q23: Streaming replay activity grouped by SIMULATED_AT hour.
-- This describes SIMULATED_AT timestamps, not guaranteed broker/network throughput.
SELECT
    DATE_TRUNC('hour', e.SIMULATED_AT) AS SIMULATED_HOUR,
    COUNT(*) AS EVENTS,
    COUNT(DISTINCT e.USER_SESSION) AS DISTINCT_SESSIONS,
    MIN(e.EVENT_TIME) AS EARLIEST_ORIGINAL_EVENT,
    MAX(e.EVENT_TIME) AS LATEST_ORIGINAL_EVENT
FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
WHERE e.SIMULATED_AT IS NOT NULL
GROUP BY 1
ORDER BY SIMULATED_HOUR;

-- Q24: User session reused by multiple users? (could be problematic mapping)
WITH session_user_counts AS (
    SELECT
        e.USER_SESSION,
        COUNT(DISTINCT e.USER_ID) AS DISTINCT_USERS
    FROM RETAIL_CLICKSTREAM_DB.RAW.RAW_CLICKSTREAM_EVENTS AS e
    WHERE e.USER_SESSION IS NOT NULL
    GROUP BY e.USER_SESSION
)
SELECT
    COUNT(*) AS DISTINCT_NON_NULL_SESSION_IDS,
    SUM(IFF(DISTINCT_USERS > 1, 1, 0)) AS SESSION_IDS_SHARED_BY_MULTIPLE_USERS,
    MAX(DISTINCT_USERS) AS MAX_USERS_PER_SESSION_ID
FROM session_user_counts;

