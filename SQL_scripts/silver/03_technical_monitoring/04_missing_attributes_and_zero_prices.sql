-- MONITOR 04: Informational missing attributes and zero-price flags.
-- NULL and price=0 are not automatically invalid. Do not delete source rows.
SELECT
    'PRODUCTS' AS DATASET,
    COUNT(*) AS ROWS_CHECKED,
    COUNT_IF(p.IS_MISSING_CATEGORY_CODE) AS MISSING_CATEGORY_ROWS,
    COUNT_IF(p.IS_MISSING_BRAND) AS MISSING_BRAND_ROWS,
    COUNT_IF(p.IS_ZERO_PRICE) AS ZERO_PRICE_ROWS,
    COUNT_IF(p.IS_ZERO_COST) AS ZERO_COST_ROWS
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_PRODUCTS AS p
UNION ALL
SELECT
    'CLICKSTREAM_EVENTS',
    COUNT(*),
    COUNT_IF(e.IS_MISSING_CATEGORY_CODE),
    COUNT_IF(e.IS_MISSING_BRAND),
    COUNT_IF(e.IS_ZERO_PRICE),
    CAST(NULL AS NUMBER) AS ZERO_COST_ROWS
FROM RETAIL_CLICKSTREAM_DB.STAGING.STG_CLICKSTREAM_EVENTS AS e;
