-- Create a dedicated database for the streaming project
CREATE DATABASE IF NOT EXISTS RETAIL_CLICKSTREAM_DB;

-- Create the RAW layer
CREATE SCHEMA IF NOT EXISTS RETAIL_CLICKSTREAM_DB.RAW;

-- Create the STAGING layer
CREATE SCHEMA IF NOT EXISTS RETAIL_CLICKSTREAM_DB.STAGING;

-- Create the MARTS layer
CREATE SCHEMA IF NOT EXISTS RETAIL_CLICKSTREAM_DB.MARTS;


-- Create a virtual warehouse
CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Verify the setup
SHOW DATABASES LIKE 'RETAIL_CLICKSTREAM_DB';

SHOW SCHEMAS IN DATABASE RETAIL_CLICKSTREAM_DB;

SHOW WAREHOUSES LIKE 'RETAIL_WH';